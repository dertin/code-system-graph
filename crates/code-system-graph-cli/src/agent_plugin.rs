/// Inputs accepted by `csgraph plugin create`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct AgentPluginCreateRequest {
    /// Workspace manifest to validate and bind.
    pub config: PathBuf,
    /// Existing graph database containing the workspace snapshot.
    pub database: PathBuf,
    /// Type-safe generation target.
    pub target: AgentPluginCreateTarget,
    /// Expose optional read-only CodeGraph-backed MCP tools.
    pub codegraph: bool,
    /// Optional absolute or resolvable `CodeGraph` executable.
    pub codegraph_binary: Option<PathBuf>,
}

/// Mutually exclusive output modes accepted by [`create_agent_plugin`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum AgentPluginCreateTarget {
    /// Generate or verify a complete portable plugin directory.
    Complete {
        /// New or already-identical output directory.
        output: PathBuf,
    },
    /// Compose a managed integration into an existing portable plugin.
    Existing {
        /// Existing portable plugin root.
        output: PathBuf,
        /// MCP server entry to add or verify.
        mcp_server_name: String,
        /// Routing skill to add or verify.
        routing_skill: String,
        /// Replace an older local receipt and binding generated by `plugin create`.
        replace_generated: bool,
    },
}

/// Output mode selected by `csgraph plugin create`.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "snake_case")]
pub enum AgentPluginCreateMode {
    /// Generate or verify the complete portable plugin.
    CompletePlugin,
    /// Add or verify one managed integration in an existing plugin.
    ExistingPlugin,
}

/// Machine-readable report returned after plugin generation or verification.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize, JsonSchema)]
#[serde(rename_all = "camelCase")]
pub struct AgentPluginCreateReport {
    /// Report schema version.
    pub schema_version: u8,
    /// Whether a complete plugin or only an existing plugin binding was created.
    pub mode: AgentPluginCreateMode,
    /// Workspace bound into the plugin.
    pub workspace: String,
    /// Stable workspace-specific plugin identity.
    pub plugin_name: String,
    /// Stable workspace-specific MCP server entry name.
    pub mcp_server_name: String,
    /// Stable workspace-specific skill name.
    pub skill_name: String,
    /// Canonical directory containing the workspace manifest.
    pub workspace_root: String,
    /// Client-managed activation semantics available in Agent Plugins 1.0.0.
    pub activation_scope: String,
    /// Absolute graph database path stored in the ignored local binding.
    pub database: String,
    /// Absolute generated plugin directory.
    pub output: String,
    /// Absolute ignored runtime binding file.
    pub binding: String,
    /// Whether the generated MCP enables `CodeGraph`.
    pub codegraph_enabled: bool,
    /// Absolute `CodeGraph` executable, when explicitly configured.
    pub codegraph_binary: Option<String>,
    /// Snapshot freshness observed during preflight.
    pub snapshot_freshness: OverallFreshness,
    /// Deterministic generated file list.
    pub files: Vec<String>,
    /// Whether a new plugin or binding was written, or an owned binding was replaced.
    pub changed: bool,
}

